//! Per-request correlation id.
//!
//! `HAProxy` can supply the id it already uses for a request — the same value its
//! `unique-id-format` puts in the access log — as an ordinary SPOE argument named
//! `req_id`. The hub adopts that value so its own log lines and the access-log
//! record name the same request. When the argument is absent, empty, the wrong
//! type, or fails validation, the hub substitutes one it generates itself, so
//! every request has an id and nothing depends on `HAProxy` cooperating.
//!
//! # The id is a label, never a key
//!
//! An adopted id is externally influenced: it arrives over the wire, and an
//! operator can point `unique-id-format` at anything. It is therefore safe to
//! *log* and safe to *return*, and it must never be used as a map key, a cache
//! key, or a deduplication token. A plugin that keyed a cache on it would let two
//! requests sharing an id share state — for a WAF transaction cache that means one
//! request's inspection state serving another's. Plugins that need an internal
//! identity must mint their own (the coraza plugin does exactly this).
//!
//! Validation exists to bound the blast radius of the *logging* use: a value that
//! reaches a log line must not be able to inject a newline, break a JSON field, or
//! grow a record without limit. The rule is deliberately the same one the
//! HAPTIC chart already applies to inbound request ids, so the stack has one
//! definition rather than two.

use abi_stable::std_types::{RHashMap, RString};
use haproxy_spoa_hub_plugin_api::SpoeValue;
use std::fmt;
use std::sync::OnceLock;
use std::sync::atomic::{AtomicU64, Ordering};

/// Well-known argument name reserved for the correlation id.
///
/// A plain argument, not `hub.`-prefixed: `hub.*` arguments are consumed and
/// stripped before plugins run, and the point of this one is that plugins can see
/// it.
pub const REQ_ID_ARG: &str = "req_id";

/// Longest adopted id accepted, in bytes.
pub const MAX_LEN: usize = 128;

/// Where the id in a message came from. Reported as a metric label; the value
/// itself is never a label (it is per-request, so it would explode cardinality).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Source {
    /// `HAProxy` supplied a valid id and the hub adopted it.
    Adopted,
    /// No usable id arrived; the hub generated one.
    Generated,
    /// An id arrived but failed validation and was replaced. The rejected value is
    /// deliberately not recorded anywhere — echoing it is the injection risk the
    /// validation exists to prevent.
    Rejected,
}

impl Source {
    /// Static label for the source metric.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Adopted => "adopted",
            Self::Generated => "generated",
            Self::Rejected => "rejected",
        }
    }
}

/// A request's correlation id, plus where it came from.
pub struct RequestId {
    value: RString,
    source: Source,
}

impl RequestId {
    /// The id, as it appears in logs and in the message arguments.
    #[must_use]
    pub fn value(&self) -> &str {
        self.value.as_str()
    }

    /// Whether the id was adopted, generated, or replaced after rejection.
    #[must_use]
    pub const fn source(&self) -> Source {
        self.source
    }
}

impl fmt::Display for RequestId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.value.as_str())
    }
}

/// Accepts `[A-Za-z0-9._:-]{1,MAX_LEN}`, ASCII only.
///
/// A byte test rather than a regex: this runs once per SPOE message, and the rule
/// is small enough that a dependency would cost more than it saves. Rejecting
/// everything outside this set is what makes the value safe to put in a log line —
/// no newline, quote, control character, or multi-byte sequence can survive it.
#[must_use]
pub fn is_valid(candidate: &str) -> bool {
    if candidate.is_empty() || candidate.len() > MAX_LEN {
        return false;
    }
    candidate
        .bytes()
        .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b':' | b'-'))
}

/// Process-unique tag, so ids generated by different hub processes on one host
/// cannot collide when their logs are shipped to the same place.
fn process_tag() -> &'static str {
    static TAG: OnceLock<String> = OnceLock::new();
    TAG.get_or_init(|| format!("{:x}", std::process::id()))
}

/// Generates an id with the same shape adopted ids must have, so a consumer never
/// has to branch on the source.
fn generate() -> RString {
    static SEQUENCE: AtomicU64 = AtomicU64::new(0);
    let n = SEQUENCE.fetch_add(1, Ordering::Relaxed);
    RString::from(format!("hub-{}-{n:x}", process_tag()))
}

/// Reads `req_id` from `args`, and guarantees that on return the entry holds a
/// valid id — adopting `HAProxy`'s when it is usable and overwriting it otherwise.
///
/// Mutates `args` in place rather than returning a new map: the arguments carry the
/// request headers and body, and the hub copies those exactly once per request. A
/// clone here to insert one small string would double that cost.
///
/// On the common path (a valid id arrived) nothing is written and nothing is
/// allocated.
pub fn normalize(args: &mut RHashMap<RString, SpoeValue>) -> RequestId {
    let supplied = args.get(&RString::from(REQ_ID_ARG));

    let source = match supplied {
        Some(SpoeValue::String(s)) if is_valid(s.as_str()) => {
            return RequestId {
                value: s.clone(),
                source: Source::Adopted,
            };
        }
        // Present but unusable: empty, over-long, wrong charset, or not a string.
        // Distinguished from absent because it is worth a metric — a config that
        // keeps sending a rejected id means the hub and the access log disagree
        // about every request's identity, and nothing else would surface that.
        Some(_) => Source::Rejected,
        None => Source::Generated,
    };

    let value = generate();
    args.insert(RString::from(REQ_ID_ARG), SpoeValue::String(value.clone()));
    RequestId { value, source }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn args_with(value: SpoeValue) -> RHashMap<RString, SpoeValue> {
        let mut args = RHashMap::new();
        args.insert(RString::from(REQ_ID_ARG), value);
        args
    }

    #[test]
    fn accepts_the_documented_charset() {
        assert!(is_valid("019f9e64-e9de-7d1b-88c9-76644f0e9b86"));
        assert!(is_valid("abcXYZ019"));
        assert!(is_valid("a.b_c:d-e"));
        assert!(is_valid(&"x".repeat(MAX_LEN)));
    }

    #[test]
    fn rejects_everything_that_could_break_a_log_line() {
        assert!(!is_valid(""), "empty");
        assert!(!is_valid(&"x".repeat(MAX_LEN + 1)), "over MAX_LEN");
        assert!(!is_valid("has space"), "space");
        assert!(!is_valid("has\nnewline"), "newline");
        assert!(!is_valid("has\ttab"), "tab");
        assert!(!is_valid("has\"quote"), "quote");
        assert!(!is_valid("has\\backslash"), "backslash");
        assert!(!is_valid("has\u{7f}del"), "delete");
        assert!(!is_valid("héllo"), "non-ascii");
        assert!(!is_valid("a{b}"), "json braces");
    }

    #[test]
    fn adopts_a_valid_supplied_id_without_touching_the_map() {
        let want = "019f9e64-e9de-7d1b-88c9-76644f0e9b86";
        let mut args = args_with(SpoeValue::String(RString::from(want)));
        let rid = normalize(&mut args);
        assert_eq!(rid.value(), want);
        assert_eq!(rid.source(), Source::Adopted);
        match args.get(&RString::from(REQ_ID_ARG)) {
            Some(SpoeValue::String(s)) => assert_eq!(
                s.as_str(),
                want,
                "an adopted id must reach plugins byte-for-byte"
            ),
            other => panic!("expected the adopted id in args, got {other:?}"),
        }
    }

    #[test]
    fn generates_when_absent_and_publishes_it_to_plugins() {
        let mut args: RHashMap<RString, SpoeValue> = RHashMap::new();
        let rid = normalize(&mut args);
        assert_eq!(rid.source(), Source::Generated);
        assert!(is_valid(rid.value()), "generated ids obey the same rule");
        match args.get(&RString::from(REQ_ID_ARG)) {
            Some(SpoeValue::String(s)) => assert_eq!(s.as_str(), rid.value()),
            other => panic!("expected the generated id in args, got {other:?}"),
        }
    }

    /// The security-relevant case: an unusable value must be REPLACED, not passed
    /// through. If it survived into `args` a plugin could log it, and a newline or
    /// quote would then break the log record.
    #[test]
    fn replaces_an_unsafe_supplied_id_rather_than_forwarding_it() {
        let over_long = "x".repeat(MAX_LEN + 1);
        // (description, value, the original text if it was a string)
        let cases: [(&str, SpoeValue, Option<&str>); 7] = [
            ("empty", SpoeValue::String(RString::from("")), Some("")),
            (
                "space",
                SpoeValue::String(RString::from("a b")),
                Some("a b"),
            ),
            (
                "newline",
                SpoeValue::String(RString::from("x\ny")),
                Some("x\ny"),
            ),
            (
                "tab",
                SpoeValue::String(RString::from("tab\there")),
                Some("tab\there"),
            ),
            (
                "quote",
                SpoeValue::String(RString::from("quote\"y")),
                Some("quote\"y"),
            ),
            (
                "over MAX_LEN",
                SpoeValue::String(RString::from(over_long.as_str())),
                Some(over_long.as_str()),
            ),
            ("wrong type", SpoeValue::Int32(7), None),
        ];

        for (what, bad, original) in cases {
            let mut args = args_with(bad);
            let rid = normalize(&mut args);
            assert_eq!(rid.source(), Source::Rejected, "{what}");
            assert!(is_valid(rid.value()), "replacement must be valid: {what}");
            match args.get(&RString::from(REQ_ID_ARG)) {
                Some(SpoeValue::String(s)) => {
                    assert_eq!(s.as_str(), rid.value(), "{what}");
                    if let Some(orig) = original {
                        assert_ne!(
                            s.as_str(),
                            orig,
                            "the rejected value must not reach a plugin: {what}"
                        );
                    }
                }
                other => panic!("expected a replacement string for {what}, got {other:?}"),
            }
        }
    }

    #[test]
    fn generated_ids_are_distinct() {
        let mut seen = std::collections::HashSet::new();
        for _ in 0..1000 {
            let mut args: RHashMap<RString, SpoeValue> = RHashMap::new();
            assert!(
                seen.insert(normalize(&mut args).value().to_owned()),
                "generated ids must not repeat within a process"
            );
        }
    }
}
